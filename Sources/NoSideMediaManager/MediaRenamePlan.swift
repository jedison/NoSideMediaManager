import Foundation

/// A reviewed, reversible set of local filename changes. It is deliberately
/// separate from metadata lookup: callers must establish episode mapping before
/// constructing a plan.
public struct MediaRename: Sendable, Equatable, Codable {
    public let source: URL
    public let destination: URL

    public init(source: URL, destination: URL) {
        self.source = source
        self.destination = destination
    }
}

public enum MediaRenameError: LocalizedError, Equatable {
    case emptyPlan
    case duplicateSource(URL)
    case duplicateDestination(URL)
    case sourceMissing(URL)
    case destinationFolderMissing(URL)
    case destinationExists(URL)

    public var errorDescription: String? {
        switch self {
        case .emptyPlan: "Rename plan contains no files."
        case .duplicateSource(let url): "A source is listed more than once: \(url.path)"
        case .duplicateDestination(let url): "More than one file would be renamed to: \(url.path)"
        case .sourceMissing(let url): "Rename source does not exist: \(url.path)"
        case .destinationFolderMissing(let url): "Rename destination folder does not exist: \(url.path)"
        case .destinationExists(let url): "Rename destination already exists: \(url.path)"
        }
    }
}

public struct MediaRenamePlan: Sendable, Equatable {
    public let renames: [MediaRename]

    public init(renames: [MediaRename]) throws {
        guard !renames.isEmpty else { throw MediaRenameError.emptyPlan }
        var sources = Set<String>()
        var destinations = Set<String>()
        for rename in renames {
            guard sources.insert(rename.source.standardizedFileURL.path).inserted else { throw MediaRenameError.duplicateSource(rename.source) }
            guard destinations.insert(rename.destination.standardizedFileURL.path).inserted else { throw MediaRenameError.duplicateDestination(rename.destination) }
        }
        self.renames = renames
    }

    /// Suitable for review or execution by the owner of the media folder.
    public func bashScript() -> String {
        let commands = renames.map { "mv -- \(shellQuote($0.source.path)) \(shellQuote($0.destination.path))" }
        return (["#!/usr/bin/env bash", "set -euo pipefail", "", "# Generated by NoSide Media Manager. Review before running."] + commands + [""]).joined(separator: "\n")
    }

    /// Returns the plan needed to undo this plan after a successful execution.
    public var reversed: MediaRenamePlan {
        // The original plan has already validated distinct source/destination paths.
        try! MediaRenamePlan(renames: renames.reversed().map { MediaRename(source: $0.destination, destination: $0.source) })
    }

    /// Executes only after every source and destination has passed preflight.
    /// The caller owns user confirmation; this method never prompts.
    public func execute(fileManager: FileManager = .default) throws {
        for rename in renames {
            guard fileManager.fileExists(atPath: rename.source.path) else { throw MediaRenameError.sourceMissing(rename.source) }
            var isDirectory: ObjCBool = false
            let parent = rename.destination.deletingLastPathComponent()
            guard fileManager.fileExists(atPath: parent.path, isDirectory: &isDirectory), isDirectory.boolValue else { throw MediaRenameError.destinationFolderMissing(parent) }
            guard !fileManager.fileExists(atPath: rename.destination.path) else { throw MediaRenameError.destinationExists(rename.destination) }
        }
        for rename in renames { try fileManager.moveItem(at: rename.source, to: rename.destination) }
    }

    private func shellQuote(_ value: String) -> String { "'\(value.replacingOccurrences(of: "'", with: "'\\\"'\\\"'"))'" }
}
